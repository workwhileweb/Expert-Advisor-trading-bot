_locale: str = os.environ.get("EA_BOT_LANG", DEFAULT_LOCALE).lower()
if _locale not in SUPPORTED:
    _locale = DEFAULT_LOCALE


def get_locale() -> str:
    return _locale


def set_locale(locale: str) -> None:
    """Set locale for current process (vi|en)."""
    global _locale
    loc = locale.lower()
    _locale = loc if loc in SUPPORTED else DEFAULT_LOCALE


def t(key: str, **kwargs: Any) -> str:
    """Translate message key; kwargs passed to str.format."""
    table = _MESSAGES.get(_locale, _MESSAGES[DEFAULT_LOCALE])
    template = table.get(key)
    if template is None:
        template = _MESSAGES[DEFAULT_LOCALE].get(key, key)
    if kwargs:
        return template.format(**kwargs)
    return template
